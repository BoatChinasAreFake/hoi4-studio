import React, { useEffect, useMemo, useRef, useState } from 'react';
import Editor, { type OnMount, type BeforeMount } from '@monaco-editor/react';
import { BookOpen, FileText, Search } from 'lucide-react';
import {
  buildCatalog,
  searchCatalog,
  describeEntry,
  lintScript,
  type CatalogEntry,
} from '../../utils/scriptCatalog';
import { searchSnippets } from '../../utils/snippets';

interface ScriptWorkbenchProps {
  onNotify?: (msg: string) => void;
}

const LANGUAGE_ID = 'hoi4script';

// monaco-editor's own types are not a direct dependency, so describe just what the providers use.
interface MonacoModel {
  getWordUntilPosition(p: MonacoPosition): { startColumn: number; endColumn: number };
  getWordAtPosition(p: MonacoPosition): { word: string } | null;
}
interface MonacoPosition {
  lineNumber: number;
  column: number;
}
let registered = false;
// Providers are registered once for the whole page, so they read the catalog from module state rather than from
// a component instance that may later unmount.
let activeCatalog: CatalogEntry[] = [];

export const ScriptWorkbench: React.FC<ScriptWorkbenchProps> = ({ onNotify }) => {
  // Start from the shared catalog so a remount keeps what was loaded before.
  const [catalog, setCatalog] = useState<CatalogEntry[]>(activeCatalog);
  const [mounted, setMounted] = useState(false);
  const [source, setValue] = useState('add_political_power = 50' + String.fromCharCode(10));
  const [query, setQuery] = useState('');
  const [snippetQuery, setSnippetQuery] = useState('');
  const editorRef = useRef<Parameters<OnMount>[0] | null>(null);
  const monacoRef = useRef<Parameters<OnMount>[1] | null>(null);
  const docsInput = useRef<HTMLInputElement>(null);

  // A catalog generated by `npm run catalog` (reads the user's own documentation folder), if present.
  useEffect(() => {
    fetch('/script_catalog.json')
      .then((r) => (r.ok ? r.json() : Promise.reject()))
      .then((data: CatalogEntry[]) => {
        if (Array.isArray(data)) setCatalog(data);
      })
      .catch(() => undefined);
  }, []);

  useEffect(() => {
    activeCatalog = catalog;
  }, [catalog]);

  const loadDocs = async (files: FileList | null) => {
    if (!files) return;
    const docs: { effects?: string; triggers?: string; modifiers?: string } = {};
    for (const f of Array.from(files)) {
      const text = await f.text();
      if (/effects_documentation/.test(f.name)) docs.effects = text;
      else if (/triggers_documentation/.test(f.name)) docs.triggers = text;
      else if (/modifiers_documentation/.test(f.name)) docs.modifiers = text;
    }
    const built = buildCatalog(docs);
    setCatalog(built);
    onNotify?.(`Loaded ${built.length} documented effects, triggers and modifiers`);
  };

  const beforeMount: BeforeMount = (monaco) => {
    if (registered) return;
    registered = true;
    monaco.languages.register({ id: LANGUAGE_ID });
    monaco.languages.setMonarchTokensProvider(LANGUAGE_ID, {
      tokenizer: {
        root: [
          [/#.*$/, 'comment'],
          [/"[^"]*"/, 'string'],
          [/\b(yes|no)\b/, 'keyword'],
          [/[-+]?\d+(\.\d+)?/, 'number'],
          [/[A-Za-z_][A-Za-z0-9_.:]*(?=\s*[=<>])/, 'type.identifier'],
          [/[{}]/, 'delimiter.bracket'],
        ],
      },
    });
    monaco.languages.registerCompletionItemProvider(LANGUAGE_ID, {
      provideCompletionItems: (model: MonacoModel, position: MonacoPosition) => {
        const word = model.getWordUntilPosition(position);
        const range = { startLineNumber: position.lineNumber, endLineNumber: position.lineNumber, startColumn: word.startColumn, endColumn: word.endColumn };
        const kindMap = { effect: monaco.languages.CompletionItemKind.Function, trigger: monaco.languages.CompletionItemKind.Property, modifier: monaco.languages.CompletionItemKind.Variable } as const;
        const items = activeCatalog.map((e) => ({
          label: e.name,
          kind: kindMap[e.kind],
          detail: `${e.kind}${e.scopes.length ? ' - ' + e.scopes.join(', ') : ''}`,
          documentation: { value: describeEntry(e) },
          insertText: `${e.name} = `,
          range,
        }));
        return { suggestions: items };
      },
    });
    monaco.languages.registerHoverProvider(LANGUAGE_ID, {
      provideHover: (model: MonacoModel, position: MonacoPosition) => {
        const w = model.getWordAtPosition(position);
        if (!w) return null;
        const hit = activeCatalog.find((e) => e.name === w.word);
        return hit ? { contents: [{ value: describeEntry(hit) }] } : null;
      },
    });
  };

  const onMount: OnMount = (editor, monaco) => {
    editorRef.current = editor;
    monacoRef.current = monaco;
    setMounted(true);
  };

  // Lint markers; `mounted` makes this run once the editor exists, not only after the first edit.
  useEffect(() => {
    const monaco = monacoRef.current;
    const model = editorRef.current?.getModel();
    if (!monaco || !model) return;
    const diags = lintScript(source, catalog.length ? catalog : undefined);
    monaco.editor.setModelMarkers(
      model,
      'hoi4-lint',
      diags.map((d) => ({
        startLineNumber: d.line,
        endLineNumber: d.line,
        startColumn: 1,
        endColumn: 200,
        message: d.message,
        severity: d.severity === 'error' ? monaco.MarkerSeverity.Error : monaco.MarkerSeverity.Warning,
      }))
    );
  }, [source, catalog, mounted]);

  const results = useMemo(() => searchCatalog(catalog, query, undefined, 30), [catalog, query]);
  const snippets = useMemo(() => searchSnippets(snippetQuery, 12), [snippetQuery]);

  const insert = (text: string) => {
    const ed = editorRef.current;
    if (!ed) return setValue((v) => v + text + String.fromCharCode(10));
    const sel = ed.getSelection();
    if (sel) ed.executeEdits('snippet', [{ range: sel, text: text + String.fromCharCode(10), forceMoveMarkers: true }]);
    ed.focus();
  };

  return (
    <div className="flex-1 flex h-full bg-[#101512] text-[#e3e5d9] overflow-hidden">
      <div className="w-80 shrink-0 border-r border-[#30392e] flex flex-col overflow-hidden text-xs">
        <div className="p-3 border-b border-[#30392e] space-y-2">
          <div className="font-bold flex items-center gap-1"><BookOpen className="h-3.5 w-3.5 text-[#d6b878]" /> Effects, triggers, modifiers</div>
          <input ref={docsInput} type="file" accept=".md" multiple className="hidden" onChange={(e) => loadDocs(e.target.files)} />
          <button onClick={() => docsInput.current?.click()} className="px-2 py-1 rounded bg-[#242d23] border border-[#3b4936] text-[#d6b878] hover:bg-[#323d2f]">
            Load game documentation (.md)
          </button>
          <p className="text-[#71806b]">
            Pick effects_documentation.md, triggers_documentation.md and modifiers_documentation.md from your game's
            <code> documentation</code> folder. {catalog.length > 0 ? `${catalog.length} entries loaded.` : 'Nothing loaded yet.'}
          </p>
          <div className="relative">
            <Search className="h-3 w-3 absolute left-2 top-2 text-[#71806b]" />
            <input value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Search e.g. add political power" className="w-full bg-[#1b221a] border border-[#30392e] rounded pl-6 pr-2 py-1" />
          </div>
        </div>
        <div className="overflow-y-auto flex-1 p-2 space-y-1">
          {results.map((e) => (
            <button key={`${e.kind}:${e.name}`} onClick={() => insert(`${e.name} = `)} className="w-full text-left bg-[#141a15] border border-[#30392e] rounded px-2 py-1 hover:border-[#d6b878]">
              <span className="font-mono text-[#d6b878]">{e.name}</span>
              <span className="text-[#71806b]"> {e.kind}{e.scopes.length ? ` - ${e.scopes.join(', ')}` : ''}</span>
              {e.doc && <div className="text-[#909b88] line-clamp-2">{e.doc}</div>}
            </button>
          ))}
        </div>
        <div className="border-t border-[#30392e] p-3 space-y-2 max-h-[45%] overflow-y-auto">
          <div className="font-bold flex items-center gap-1"><FileText className="h-3.5 w-3.5 text-[#d6b878]" /> Snippet library</div>
          <input value={snippetQuery} onChange={(e) => setSnippetQuery(e.target.value)} placeholder="Search e.g. gain political power" className="w-full bg-[#1b221a] border border-[#30392e] rounded px-2 py-1" />
          {snippets.map((s) => (
            <button key={s.id} onClick={() => insert(s.code)} className="w-full text-left bg-[#141a15] border border-[#30392e] rounded px-2 py-1 hover:border-[#d6b878]">
              <div className="font-semibold">{s.title}</div>
              <div className="text-[#71806b]">{s.context}</div>
            </button>
          ))}
        </div>
      </div>
      <div className="flex-1 min-w-0">
        <Editor
          height="100%"
          language={LANGUAGE_ID}
          theme="vs-dark"
          value={source}
          beforeMount={beforeMount}
          onMount={onMount}
          onChange={(v) => setValue(v ?? '')}
          options={{ minimap: { enabled: false }, fontSize: 13, scrollBeyondLastLine: false, tabSize: 4, insertSpaces: false }}
        />
      </div>
    </div>
  );
};
